// Generates src/app/theme-palette.css from Tailwind's default palette.
//
//   node scripts/gen-theme-palette.mjs
//
// Most pages still style with Tailwind's palette directly (bg-white, text-zinc-700,
// bg-amber-50 …). Tailwind v4 reads those through CSS variables, so the Dark and
// Black & white themes can repaint every page by overriding the variables:
// - Dark: greys map onto the dark theme's tokens; every other hue's scale is
//   flipped (50 ↔ 950, 100 ↔ 900 …), so a pale badge becomes a deep one and dark
//   text on it becomes light.
// - Black & white: every colour keeps its lightness and loses its hue.
// Re-run after upgrading Tailwind.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const theme = fs.readFileSync(path.join(root, "node_modules/tailwindcss/theme.css"), "utf8");

const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d{2,3}):\s*(oklch\([^)]*\));/g)) {
  (palette[m[1]] ??= {})[m[2]] = m[3];
}

const GREYS = ["zinc", "gray", "neutral", "slate", "stone"];
// The dark theme's own greys (globals.css tokens), from page to brightest ink.
const DARK_GREYS = {
  50: "#13161b",
  100: "#1e222a",
  200: "#2a2e37",
  300: "#3a3f4a",
  400: "#6b717d",
  500: "#8c92a0",
  600: "#a3a8b3",
  700: "#c4c8cf",
  800: "#dcdfe4",
  900: "#ecedef",
  950: "#f4f5f6",
};

const dark = ["  --color-white: #171a20;", "  --color-black: #ffffff;"];
const mono = [];
for (const [hue, shades] of Object.entries(palette)) {
  for (const [shade, value] of Object.entries(shades)) {
    if (GREYS.includes(hue)) {
      dark.push(`  --color-${hue}-${shade}: ${DARK_GREYS[shade]};`);
    } else {
      const flipped = shades[String(1000 - Number(shade))];
      if (flipped && shade !== "500") dark.push(`  --color-${hue}-${shade}: ${flipped};`);
    }
    const lightness = value.match(/oklch\(([\d.]+%?)/)?.[1];
    if (lightness) mono.push(`  --color-${hue}-${shade}: oklch(${lightness} 0 0);`);
  }
}

const css = `/* Generated by scripts/gen-theme-palette.mjs from Tailwind ${JSON.parse(
  fs.readFileSync(path.join(root, "node_modules/tailwindcss/package.json"), "utf8"),
).version}'s palette. Don't edit by hand. */

:root[data-theme="dark"] {
${dark.join("\n")}
}

:root[data-theme="mono"] {
${mono.join("\n")}
}
`;
fs.writeFileSync(path.join(root, "src/app/theme-palette.css"), css);
console.log(`wrote src/app/theme-palette.css (${dark.length} dark, ${mono.length} mono overrides)`);
